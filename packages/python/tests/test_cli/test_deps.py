"""Tests for the ``ghagen deps`` CLI subcommands.

Scope, deliberately narrow: what is genuinely CLI. Argument parsing and
validation, token resolution, **which stream** each piece of output goes to,
and the end-to-end shape of the JSON payload.

What is *not* here, and why:

- Engine behaviour (bump detection, stale-lockfile detection, mode dispatch,
  warnings) is asserted directly, without a ``CliRunner``, in
  ``tests/test_pin/test_engine.py``.
- Output rendering (all four formats, the golden fixtures, the JSON key set) is
  asserted directly against ``ghagen.pin.render`` in
  ``tests/test_pin/test_render.py``.

Before proposal 17 this file was 911 lines, 542 of which spun up a temp
project, wrote a config, patched two ``GitHubClient`` methods and drove a Typer
command in order to re-assert facts those two files already assert in ~17 lines
with a canned transport. The renderer had no seam in Python -- the mode x
format dispatch lived inside ``deps_upgrade``, whose parameters are all Typer
``OptionInfo`` sentinels -- so a ``CliRunner`` was the only way in.
"""

from __future__ import annotations

import json
from pathlib import Path
from unittest.mock import patch

from typer.testing import CliRunner

from ghagen.cli.main import app

runner = CliRunner()


_CONFIG = """\
from ghagen import App, Job, On, PushTrigger, Step, Workflow

app = App()
ci = Workflow(
    name="CI",
    on=On(push=PushTrigger(branches=["main"])),
    jobs={"test": Job(
        runs_on="ubuntu-latest",
        steps=[Step(uses="actions/checkout@v4")],
    )},
)
app.add_workflow(ci, "ci.yml")
"""


_LOCKFILE = """\
# Auto-generated by `ghagen deps pin`. Do not edit manually.

pins:
  actions/checkout@v4:
    sha: "0123456789abcdef0123456789abcdef01234567"
    resolved_at: "2026-04-09T00:00:00+00:00"
"""


def test_deps_check_synced_passes_when_lockfile_in_sync(
    tmp_path: Path, monkeypatch: object
):
    monkeypatch.chdir(tmp_path)  # type: ignore[attr-defined]
    monkeypatch.delenv("GITHUB_TOKEN", raising=False)  # type: ignore[attr-defined]
    monkeypatch.delenv("GH_TOKEN", raising=False)  # type: ignore[attr-defined]

    (tmp_path / "ghagen_config.py").write_text(_CONFIG)
    lockfile = tmp_path / ".ghagen.lock.yml"
    lockfile.write_text(_LOCKFILE)

    result = runner.invoke(app, ["deps", "check-synced"])
    assert result.exit_code == 0, result.output
    assert "Lockfile is in sync." in result.output
    # check-synced never hits the network, so the no-token warning must NOT fire.
    assert "no GitHub token found" not in result.output


def test_deps_check_synced_fails_when_entry_missing(
    tmp_path: Path, monkeypatch: object
):
    monkeypatch.chdir(tmp_path)  # type: ignore[attr-defined]
    monkeypatch.delenv("GITHUB_TOKEN", raising=False)  # type: ignore[attr-defined]
    monkeypatch.delenv("GH_TOKEN", raising=False)  # type: ignore[attr-defined]

    (tmp_path / "ghagen_config.py").write_text(_CONFIG)
    # Deliberately create an empty lockfile so the check sees a missing entry.
    lockfile = tmp_path / ".ghagen.lock.yml"
