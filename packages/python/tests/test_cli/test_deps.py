"""Tests for the ``ghagen deps`` CLI subcommands.

Scope, deliberately narrow: what is genuinely CLI. Argument parsing and
validation, token resolution, **which stream** each piece of output goes to,
and the end-to-end shape of the JSON payload.

What is *not* here, and why:

- Engine behaviour (bump detection, stale-lockfile detection, mode dispatch,
  warnings) is asserted directly, without a ``CliRunner``, in
  ``tests/test_pin/test_engine.py``.
- Output rendering (all four formats, the golden fixtures, the JSON key set) is
  asserted directly against ``ghagen.pin.render`` in
  ``tests/test_pin/test_render.py``.

Before proposal 17 this file was 911 lines, 542 of which spun up a temp
project, wrote a config, patched two ``GitHubClient`` methods and drove a Typer
command in order to re-assert facts those two files already assert in ~17 lines
with a canned transport. The renderer had no seam in Python -- the mode x
format dispatch lived inside ``deps_upgrade``, whose parameters are all Typer
``OptionInfo`` sentinels -- so a ``CliRunner`` was the only way in.
"""

