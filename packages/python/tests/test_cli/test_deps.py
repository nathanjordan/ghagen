class TestUpgradeErrorHandling:
    """Flag validation and warning routing."""

    def test_invalid_mode(self, tmp_path, monkeypatch):
        monkeypatch.chdir(tmp_path)
        monkeypatch.setenv("GITHUB_TOKEN", "fake-token")
        _setup_upgrade_project(tmp_path)

        result = runner.invoke(app, ["deps", "upgrade", "--mode", "invalid"])
        assert result.exit_code == 2
        assert "unknown --mode value" in result.output

    def test_invalid_format(self, tmp_path, monkeypatch):
        """``--format`` validation stays at the CLI edge, beside ``--mode``.

        ``pin.render`` treats an unknown format as a programmer error; the
        command is what turns a bad flag into exit 2.
        """
        monkeypatch.chdir(tmp_path)
        monkeypatch.setenv("GITHUB_TOKEN", "fake-token")
        _setup_upgrade_project(tmp_path)

        result = runner.invoke(app, ["deps", "upgrade", "--format", "yaml"])
        assert result.exit_code == 2
        assert "unknown --format value" in result.output

    @patch("ghagen.pin.sources.track_user_files", side_effect=_mock_track_user_files)
    def test_warnings_are_echoed_to_stderr(self, mock_track, tmp_path, monkeypatch):
        """A ``report.warnings`` entry reaches stderr with the ``warning: `` prefix.

        The engine fact -- that a failed tag lookup becomes a warning rather
        than an exception -- is asserted in
        ``test_pin/test_engine.py::TestUpgrade``. This is the CLI half: the
        echo loop's routing, which must not pollute the machine-readable
        stdout payload.
        """
        monkeypatch.chdir(tmp_path)
        monkeypatch.setenv("GITHUB_TOKEN", "fake-token")
        _setup_upgrade_project(tmp_path)

        from ghagen.pin.github import ResolveError

        def mock_tags_with_error(owner, repo, *, token=None):
            if repo == "checkout":
                raise ResolveError("rate limited")
            return _SETUP_PYTHON_TAGS

        with patch(
            "ghagen.pin.github.GitHubClient.list_tags",
            side_effect=mock_tags_with_error,
        ):
            result = runner.invoke(
                app,
                [
                    "deps",
                    "upgrade",
                    "--mode",
                    "versions",
                    "--format",
                    "json",
                    "--check",
                ],
            )

        assert result.exit_code == 0, result.output
        assert "warning: failed to list tags for actions/checkout" in result.stderr
        assert "rate limited" in result.stderr
        assert "warning:" not in result.stdout

        # The other repo is still reported on a parseable stdout.
        data = json.loads(result.stdout)
        uses_list = [b["uses"] for b in data["version_bumps"]]
        assert "actions/setup-python@v5" in uses_list


class TestUpgradeJsonContract:
    """The end-to-end key-set contract.

    The rule itself -- key presence follows ``checked_versions`` /
    ``checked_lockfile`` -- is asserted directly on the renderer in
    ``tests/test_pin/test_render.py``. This is the one place it is pinned
    through the real command, because it is a user-visible payload change.
    """

    def test_empty_report_emits_only_the_keys_the_mode_asked_for(
        self, tmp_path, monkeypatch
    ):
        """An empty report emits the same key set as a non-empty one.

        The key set depends only on ``--mode``, which the caller chose, and
        never on whether the run happened to find anything.  This inverts the
        behaviour the 'everything up to date' early return used to have, and
        resolves the open choice recorded in
        ``docs/specs/0005-typed-engine-report-seam.md`` Section 2.2.
        """
        monkeypatch.chdir(tmp_path)
        monkeypatch.setenv("GITHUB_TOKEN", "fake-token")

        config = tmp_path / "ghagen_config.py"
        config.write_text(
            """\
from ghagen import App, Job, On, PushTrigger, Step, Workflow

app = App()
ci = Workflow(
    name="CI",
    on=On(push=PushTrigger(branches=["main"])),
    jobs={"test": Job(
        runs_on="ubuntu-latest",
        steps=[Step(name="Test", run="echo hello")],
    )},
)
app.add_workflow(ci, "ci.yml")
"""
        )

        with patch(
            "ghagen.pin.sources.track_user_files",
            side_effect=_mock_track_user_files,
        ):
            expected_per_mode = {
                "versions": {"version_bumps": []},
                "lockfile": {"lockfile_stale": []},
                "all": {"version_bumps": [], "lockfile_stale": []},
            }
            for mode, expected in expected_per_mode.items():
                result = runner.invoke(
                    app,
                    ["deps", "upgrade", "--mode", mode, "--format", "json", "--check"],
                )
                assert result.exit_code == 0, result.output
                data = json.loads(result.stdout)
                assert data == expected, mode
                assert "helper_provided" not in result.output
