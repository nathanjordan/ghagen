"""The CLI stream contract, driven from ``schema/cli-streams.yml``.

This is the shared table both ports must satisfy: for a given command (and,
where the rule is conditional, a given flag combination) exactly one of
``stdout``/``stderr`` carries the described output. The TypeScript mirror is
``packages/typescript/src/cli/streams.test.ts``.

Every case below invokes the real command and asks the table which stream the
row's marker text belongs on, rather than hard-coding "stdout" or "stderr" in
the assertion. Corrupting a row in ``schema/cli-streams.yml`` therefore fails
the corresponding case here *and* the TypeScript mirror, which is the whole
point of a shared oracle: see docs/issues/24-conformance-gaps-is-inert.md for
what happens to a table nothing actually reads.

``click.testing.Result.output`` (Python) mixes stdout and stderr in write
order, so it cannot stand in for either column here -- every assertion below
reads ``result.stdout``/``result.stderr`` directly, indexed through the row.
"""

from __future__ import annotations

from pathlib import Path
from unittest.mock import patch

from ruamel.yaml import YAML
from typer.testing import CliRunner

from ghagen.cli.main import app
from ghagen.pin.engine import PinReport, ResolvedPin
from ghagen_schema.paths import SCHEMA_DIR

runner = CliRunner()

_TABLE: dict[str, dict[str, str]] = {
    row["id"]: row
    for row in YAML(typ="safe").load((SCHEMA_DIR / "cli-streams.yml").read_text())
}

assert _TABLE, "schema/cli-streams.yml is empty -- every case below would be vacuous"


def _stream(result, row_id: str) -> str:
    """The text of the stream ``schema/cli-streams.yml`` names for *row_id*."""
    return result.stdout if _TABLE[row_id]["stream"] == "stdout" else result.stderr


def _other_stream(result, row_id: str) -> str:
    """The text of the *other* stream -- what the marker must be absent from."""
    return result.stderr if _TABLE[row_id]["stream"] == "stdout" else result.stdout


