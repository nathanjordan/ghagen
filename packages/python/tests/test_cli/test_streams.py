# -- deps upgrade -----------------------------------------------------------


class TestDepsUpgradeStreams:
    @patch("ghagen.pin.sources.track_user_files", side_effect=_mock_track_user_files)
    @patch("ghagen.pin.github.GitHubClient.list_tags", side_effect=_mock_list_tags)
    def test_report_always_on_stdout(
        self, mock_tags, mock_track, tmp_path, monkeypatch
    ):
        """The rendered report owns stdout whether or not --format is passed."""
        monkeypatch.chdir(tmp_path)
        monkeypatch.setenv("GITHUB_TOKEN", "fake-token")
        (tmp_path / "ghagen_config.py").write_text(_UPGRADE_CONFIG)

        result = runner.invoke(
            app,
            ["deps", "upgrade", "--mode", "versions", "--format", "json", "--check"],
        )
        assert result.exit_code == 0, (result.stdout, result.stderr)
        assert '"version_bumps"' in _stream(result, "deps-upgrade-report")
        assert '"version_bumps"' not in _other_stream(result, "deps-upgrade-report")

    @patch("ghagen.pin.sources.track_user_files", side_effect=_mock_track_user_files)
    def test_warning_always_on_stderr(self, mock_track, tmp_path, monkeypatch):
        monkeypatch.chdir(tmp_path)
        monkeypatch.setenv("GITHUB_TOKEN", "fake-token")
        (tmp_path / "ghagen_config.py").write_text(_UPGRADE_CONFIG)

        from ghagen.pin.github import ResolveError

        def mock_tags_with_error(owner, repo, *, token=None):
            if repo == "checkout":
                raise ResolveError("rate limited")
            return _SETUP_PYTHON_TAGS

        with patch(
            "ghagen.pin.github.GitHubClient.list_tags", side_effect=mock_tags_with_error
        ):
            result = runner.invoke(
                app,
                [
                    "deps",
                    "upgrade",
                    "--mode",
                    "versions",
                    "--format",
                    "json",
                    "--check",
                ],
            )

        assert result.exit_code == 0, (result.stdout, result.stderr)
        assert "warning:" in _stream(result, "deps-upgrade-warning")
        assert "warning:" not in _other_stream(result, "deps-upgrade-warning")

    @patch("ghagen.pin.sources.track_user_files", side_effect=_mock_track_user_files)
    @patch("ghagen.pin.github.GitHubClient.list_tags", side_effect=_mock_list_tags)
    def test_progress_note_without_format_is_stdout(
        self, mock_tags, mock_track, tmp_path, monkeypatch
    ):
        monkeypatch.chdir(tmp_path)
        monkeypatch.setenv("GITHUB_TOKEN", "fake-token")
        (tmp_path / "ghagen_config.py").write_text(_UPGRADE_CONFIG)

        result = runner.invoke(app, ["deps", "upgrade", "--mode", "versions"])
        assert result.exit_code == 0, (result.stdout, result.stderr)
        row = "deps-upgrade-progress-note-no-format"
        assert "Applied version bumps" in _stream(result, row)
        assert "Applied version bumps" not in _other_stream(result, row)

    @patch("ghagen.pin.sources.track_user_files", side_effect=_mock_track_user_files)
    @patch("ghagen.pin.github.GitHubClient.list_tags", side_effect=_mock_list_tags)
    def test_progress_note_with_format_is_stderr(
        self, mock_tags, mock_track, tmp_path, monkeypatch
    ):
        """The H6 hotfix: --format flips the progress note off stdout."""
        monkeypatch.chdir(tmp_path)
        monkeypatch.setenv("GITHUB_TOKEN", "fake-token")
        (tmp_path / "ghagen_config.py").write_text(_UPGRADE_CONFIG)

        result = runner.invoke(
            app, ["deps", "upgrade", "--mode", "versions", "--format", "json"]
        )
        assert result.exit_code == 0, (result.stdout, result.stderr)
        row = "deps-upgrade-progress-note-with-format"
        assert "Applied version bumps" in _stream(result, row)
        assert "Applied version bumps" not in _other_stream(result, row)


